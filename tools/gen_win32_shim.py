def main() -> int:
    pe = PE(str(IMAGE))
    rows = pe.imports()
    names = sorted({row["name"] for row in rows if row.get("name")})
    ident = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")
    lines = [HEADER]
    emitted = set(CRT_SIGNATURES)
    for name, sig in sorted(CRT_SIGNATURES.items()):
        if sig.endswith("=") or name.endswith("="):
            continue
        if name in ("_ftol", "_ftol2", "_CIpow", "_CIsin", "_CIcos", "_CIfmod") and name not in names:
            pass  # declare anyway; helpers exist in the image CRT tail
        lines.append(f'extern "C" {sig};\n')
    for name in names:
        if not ident.match(name) or name in emitted:
            continue
        if name in ("_CxxThrowException", "_purecall"):
            continue  # predeclared by the compiler frontend; redeclaring conflicts
        lines.append(f'extern "C" void __declspec(dllimport) {name}(...);\n')
    lines.append(FOOTER)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("".join(lines))
    kept = sum(1 for n in names if ident.match(n) and n not in CRT_SIGNATURES) + len(CRT_SIGNATURES)
    print(f"imports={len(names)} declared={kept} out={OUT.relative_to(ROOT)}")
    json.dump({"imports": len(names), "declared": kept}, open(OUT.parent / "shim.json", "w"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
